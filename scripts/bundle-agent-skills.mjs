import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const roleSources = {
  reviewer: ['code-review-collaboration'],
  impact: ['product-planning', 'Impact'],
  triage: ['product-planning', 'Triage'],
  qa: ['quality-assurance'],
  release: ['release-management'],
  docs: ['developer-documentation'],
  architect: ['technical-architecture']
};

const [checkout, revision, mode] = process.argv.slice(2);
if (!checkout || !/^[a-f0-9]{40}$/.test(revision ?? '') || (mode !== undefined && mode !== '--check') || process.argv.length > 5) {
  throw new Error('Use node scripts/bundle-agent-skills.mjs <catalog-checkout> <full commit SHA> [--check]');
}

function runtimeGuidance(markdown, roleSection, path) {
  const lines = markdown.split(/\r?\n/);
  const start = lines.indexOf('## Runtime advisory guidance');
  if (start === -1 || start !== lines.lastIndexOf('## Runtime advisory guidance')) throw new Error('Expected one runtime guidance section in ' + path);
  const next = lines.findIndex((line, index) => index > start && /^#{1,2} /.test(line));
  const section = lines.slice(start + 1, next === -1 ? lines.length : next);
  const roleHeadings = section.flatMap((line, index) => /^### /.test(line) ? [index] : []);
  let roleLines = section;
  if (roleSection) {
    const headings = roleHeadings.filter(index => section[index] === '### ' + roleSection);
    if (headings.length !== 1) throw new Error('Expected one role section in ' + path + ' for ' + roleSection);
    const roleEnd = roleHeadings.find(index => index > headings[0]) ?? section.length;
    roleLines = section.slice(headings[0] + 1, roleEnd);
  } else if (roleHeadings.length) {
    throw new Error('Unexpected nested role sections in ' + path);
  }
  const text = roleLines.join('\n').trim();
  if (!text.startsWith('- ') || Buffer.byteLength(text, 'utf8') > 2_400) throw new Error('Runtime guidance must be bounded nonempty bullets in ' + path);
  return text;
}

const roles = Object.fromEntries(Object.entries(roleSources).map(([role, [name, section]]) => {
  const path = `skills/oddmash-${name}/SKILL.md`;
  const markdown = execFileSync('git', ['-C', checkout, 'show', `${revision}:${path}`], { encoding: 'utf8', maxBuffer: 100_000 });
  return [role, { path, text: runtimeGuidance(markdown, section, path) }];
}));
const output = new URL('../src/agent-skill-bundle.ts', import.meta.url);
const generated = '// Generated by scripts/bundle-agent-skills.mjs. Update the source catalog and regenerate.\n' +
  `export const skillRevision = ${JSON.stringify(revision)};\n` +
  `export const bundledAgentSkills = ${JSON.stringify(roles, null, 2)} as const;\n`;
if (mode === '--check') {
  if (readFileSync(output, 'utf8') !== generated) throw new Error('The bundled runtime guidance differs from the pinned catalog revision');
} else writeFileSync(output, generated);
