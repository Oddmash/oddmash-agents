import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../apps/console/src/console-tokens.json', import.meta.url);
const template = new URL('../apps/console/src/globals.template.css', import.meta.url);
const output = new URL('../apps/console/src/globals.css', import.meta.url);
const tokenName = /^[a-z][a-z0-9-]*$/;
const tokenValue = /^(?:-?(?:\d+|\d*\.\d+)(?:px|ch|em|ms)?|system-ui, sans-serif|ui-monospace, monospace)$/;

function render() {
  const tokens = JSON.parse(readFileSync(source, 'utf8'));
  const input = readFileSync(template, 'utf8');
  const variables = Object.entries(tokens.variables).map(([name, value]) => {
    if (!tokenName.test(name) || typeof value !== 'string' || !tokenValue.test(value)) throw new Error('Invalid console token: ' + name);
    return '  --console-' + name + ': ' + value + ';';
  });
  for (const match of input.matchAll(/var\(--console-([a-z0-9-]+)\)/g)) {
    if (!Object.hasOwn(tokens.variables, match[1])) throw new Error('Unknown console token: ' + match[1]);
  }
  const marker = '{{variables}}';
  if (input.split(marker).length !== 2) throw new Error('Expected exactly one variables marker');
  const css = input.replace(marker, variables.join('\n')).replace(/\{\{breakpoint:([a-z0-9-]+)\}\}/g, (_, name) => {
    const value = tokens.breakpoints[name];
    if (!Object.hasOwn(tokens.breakpoints, name) || typeof value !== 'string' || !/^\d+px$/.test(value)) throw new Error('Invalid console breakpoint: ' + name);
    return value;
  });
  if (/\{\{[^}]+\}\}/.test(css)) throw new Error('Unexpected unresolved console style marker');
  return '/* Generated by node scripts/generate-console-tokens.mjs. Edit console-tokens.json or globals.template.css. */\n' + css;
}

const css = render();
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== css) throw new Error('Console tokens are out of date. Run node scripts/generate-console-tokens.mjs.');
} else {
  writeFileSync(output, css);
}
